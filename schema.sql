CREATE DATABASE IF NOT EXISTS careloop CHARACTER SET utf8mb4;
USE careloop;
CREATE TABLE IF NOT EXISTS users(
 id INT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(120) NOT NULL UNIQUE,
 pass_hash VARCHAR(100) NOT NULL, elder_name VARCHAR(60) NOT NULL,
 created_at DATETIME DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS events(
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL,
 type ENUM('door','motion','kitchen','alexa','tv','med_ack') NOT NULL,
 created_at DATETIME DEFAULT CURRENT_TIMESTAMP, INDEX(user_id,created_at),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS alerts(
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, level TINYINT NOT NULL,
 channel VARCHAR(30) NOT NULL, reason VARCHAR(300) NOT NULL, acked TINYINT DEFAULT 0,
 created_at DATETIME DEFAULT CURRENT_TIMESTAMP, INDEX(user_id,created_at),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE);
